## 03_panelD_permutation_test.R
## Generate Panel D: permutation test of KO-compound proximity

library(MetaPathNet)
library(ggplot2)

if (!exists("app_network_extended")) {
  stop("Object 'app_network_extended' not found. Run 00_build_network_inputs.R first.")
}

if (!exists("app_gene_nodes") || !exists("app_compound_nodes")) {
  stop("Objects 'app_gene_nodes' and/or 'app_compound_nodes' not found. Run 00_build_network_inputs.R first.")
}

## Check selected KOs and compounds in the extended network
app_gene_mapped <- MetaPathNet::findMappedNodes(
  nodes         = app_gene_nodes,
  network_table = app_network_extended
)

app_compound_mapped <- MetaPathNet::findMappedNodes(
  nodes         = app_compound_nodes,
  network_table = app_network_extended
)

## Keep mapped nodes only for permutation testing
app_gene_mapped_nodes <- app_gene_mapped$mapped_nodes
app_compound_mapped_nodes <- app_compound_mapped$mapped_nodes

if (length(app_gene_mapped_nodes) == 0) {
  stop("No selected KO nodes were mapped to app_network_extended.")
}

if (length(app_compound_mapped_nodes) == 0) {
  stop("No selected compound nodes were mapped to app_network_extended.")
}

## Run permutation test
app_perm_tma <- MetaPathNet::permutePaths(
  network_table = app_network_extended,
  source_nodes  = app_gene_mapped_nodes,
  target_nodes  = app_compound_mapped_nodes,
  n_perm        = 10000,
  mode          = "out",
  plot          = FALSE,
  return_perm   = TRUE
)

## View permutation summary statistics
app_perm_tma$stats

## Permutation distribution plot
## A default plot can also be generated by setting plot = TRUE in permutePaths().
## Here, ggplot2 is used separately to allow more flexible figure styling.
app_perm_df <- data.frame(
  random_sp = app_perm_tma$random_sp
)

app_observed_sp  <- app_perm_tma$stats$observed_sp
app_mean_perm_sp <- app_perm_tma$stats$mean_perm_sp
app_p_value      <- app_perm_tma$stats$p_value

## Generate custom permutation distribution plot
app_perm_plot <- ggplot2::ggplot(
  app_perm_df,
  ggplot2::aes(x = random_sp)
) +
  ggplot2::geom_histogram(
    ggplot2::aes(y = ggplot2::after_stat(density)),
    bins  = 40,
    fill  = "#9DC7DD",
    color = "white",
    alpha = 1
  ) +
  ggplot2::geom_density(
    linewidth = 1,
    color     = "#9ED17B"
  ) +
  ggplot2::geom_vline(
    xintercept = app_observed_sp,
    color      = "#C45745",
    linewidth  = 1,
    linetype   = "dashed"
  ) +
  ggplot2::geom_vline(
    xintercept = app_mean_perm_sp,
    color      = "#4D4D4D",
    linewidth  = 1,
    linetype   = "dotted"
  ) +
  ggplot2::scale_x_continuous(
    breaks = seq(0, 20, by = 2)
  ) +
  ggplot2::coord_cartesian(
    xlim = c(0, 20)
  ) +
  ggplot2::labs(
    x = "Mean shortest path length",
    y = "Density"
  ) +
  ggplot2::theme_void(base_size = 14) +
  ggplot2::theme(
    axis.text.x  = ggplot2::element_text(size = 14, color = "black"),
    axis.text.y  = ggplot2::element_text(size = 14, color = "black"),
    axis.title.x = ggplot2::element_text(size = 14, color = "black"),
    axis.title.y = ggplot2::element_text(size = 14, color = "black"),
    axis.line.x  = ggplot2::element_line(color = "black"),
    axis.line.y  = ggplot2::element_line(color = "black")
  )

## Show custom plot
print(app_perm_plot)

